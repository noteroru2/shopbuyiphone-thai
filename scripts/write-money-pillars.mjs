/** @param {string} base */
function growToTarget(base) {
  let out = base;
  let n = 0;
  while (countThWords(out) < TARGET) {
    const chunk = expansionChunks[n % expansionChunks.length].replace(
      /^## /,
      `## ภาคผนวกเชิงปฏิบัติ (${n + 1}) — `,
    );
    out += `\n\n${chunk}`;
    n += 1;
    if (n > 400) break;
  }
  return out;
}

