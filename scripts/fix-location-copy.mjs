const files = fs.readdirSync(dir).filter((f) => f.endsWith('.md'));
let changed = 0;
for (const fname of files) {
  const fp = path.join(dir, fname);
  let s = fs.readFileSync(fp, 'utf8');
  const orig = s;
  s = applyMechanical(s);
  if (descriptions[fname]) {
    s = replaceDescription(s, descriptions[fname]);
  }
  s = replaceFirstBodyParagraph(s, fname);
  s = patchKalasinDuplicateFaq(s, fname);
  s = patchBuriramFaqQuestion(s, fname);
  if (s !== orig) {
    fs.writeFileSync(fp, s, 'utf8');
    changed++;
  }
}
