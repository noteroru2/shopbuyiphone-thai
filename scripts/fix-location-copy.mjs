function applyMechanical(s) {
  s = s.replace(/ราคาประเมินiPhone/g, 'ราคาประเมิน iPhone');
  s = s.replace(/ราคาประเมิน iPhoneใน/g, 'ราคาประเมิน iPhone ใน');
  s = s.replace(/iPhoneเสีย/g, 'iPhone เสีย');
  s = s.replace(/iPhoneเปิด/g, 'iPhone เปิด');
  s = s.replace(/ผู้ใช้ iPhoneจำนวน/g, 'ผู้ใช้ iPhone จำนวน');
  s = s.replace(/ผู้ใช้ iPhoneใน/g, 'ผู้ใช้ iPhone ใน');
  s = s.replace(/ผู้ใช้ iPhoneทั้ง/g, 'ผู้ใช้ iPhone ทั้ง');
  s = s.replace(/ผู้ใช้ iPhoneมี/g, 'ผู้ใช้ iPhone มี');
  s = s.replace(/ผู้ใช้ iPhoneจึง/g, 'ผู้ใช้ iPhone จึง');
  s = s.replace(/ใช้iPhoneเป็น/g, 'ใช้ iPhone เป็น');
  const badBlock =
    'รวมถึง iPhone รุ่น Pro / Pro Max และ iPhone โดยดูจากรุ่นและสภาพจริงเป็นหลัก';
  const goodBlock = 'รวมถึงสาย Pro / Pro Max โดยประเมินจากรุ่นและสภาพจริงเป็นหลัก';
  s = s.split(badBlock).join(goodBlock);
  const badBlock2 =
    'รวมถึง iPhone รุ่น Pro / Pro Max และ iPhone โดยดูจากรุ่นและสภาพจริง';
  const goodBlock2 = 'รวมถึงสาย Pro / Pro Max โดยประเมินจากรุ่นและสภาพจริง';
  s = s.split(badBlock2).join(goodBlock2);
  const linkDup =
    ' · [iPhone](/รับซื้อไอโฟน/pro-max/) · [iPhone รุ่น Pro / Pro Max](/รับซื้อไอโฟน/pro-max/)';
  const linkOne = ' · [สาย Pro / Pro Max](/รับซื้อไอโฟน/pro-max/)';
  s = s.split(linkDup).join(linkOne);
  return s;
}

function replaceDescription(s, newDesc) {
  return s.replace(/^description: .+$/m, `description: ${newDesc}`);
}

/** แทนที่ย่อหน้าแรกหลัง frontmatter จนถึงบล็อกลิงก์ภาค */
function replaceFirstBodyParagraph(s, fname) {
  const intro = introByFile[fname];
  if (!intro) return s;
  const anchor = '\n\nหากต้องการภาพรวมทั้งภาค';
  const re = /^---\r?\n[\s\S]*?\r?\n---\r?\n/;
  const m = s.match(re);
  if (!m) return s;
  const head = m[0];
  const rest = s.slice(head.length);
  const pos = rest.indexOf(anchor);
  if (pos === -1) return s;
  return head + intro + rest.slice(pos);
}

